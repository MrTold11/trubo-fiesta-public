package ru.chmod777.trubofiesta.algo;

/**
 * Алгоритм трассировки: по нормализованному миру строит варианты подключения всех точек
 * подключения ОКС к существующей тепловой сети.
 *
 * Границы намеренно узкие. Снаружи остаётся всё, что не должно зависеть от реализации:
 * разбор входа, граф существующей сети, отступы и правила пересечений, точки подхода к ОКС,
 * подбор условного диаметра, стоимость и ранжирование. Внутри — только то, что напрямую
 * определяет результат: где искать трассу, как соединять точки подключения в дерево,
 * где ставить камеры и как доводить геометрию.
 *
 * Поэтому новую реализацию можно добавить рядом и сравнить с существующей на тех же данных,
 * ничего в них не меняя: достаточно объявить бин с другим {@link #key()}.
 */
public interface RoutingAlgorithm {

    /** Ключ для параметра расчёта {@code algorithm}. */
    String key();

    /** Название для интерфейса и журнала. */
    String title();

    /**
     * Строит и доводит кандидатов. Реализация вправе построить их сколько угодно: отбор
     * до трёх вариантов и ранжирование выполняются снаружи по показателю раздела 6.
     */
    AlgorithmResult plan(AlgorithmContext context, ProgressLog log);
}
