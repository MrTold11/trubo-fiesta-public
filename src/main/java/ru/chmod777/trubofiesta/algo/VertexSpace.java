package ru.chmod777.trubofiesta.algo;

import org.locationtech.jts.geom.Coordinate;

/**
 * Пространство вершин, в котором алгоритм выражает построенную сеть. {@link NewNetwork}
 * хранит только номера вершин и рёбра между ними, а во что эти номера превращаются в плане,
 * знает алгоритм: у сеточного это узлы сетки и точки на лучах, у другого — что угодно ещё.
 *
 * Благодаря этому оценка варианта (расходы, диаметры, камеры, стоимость) не зависит от того,
 * как алгоритм искал трассу: ей достаточно уметь спросить координату вершины.
 */
public interface VertexSpace {

    /** Координата вершины в плане, EPSG:32637. */
    Coordinate vertex(int index);

    /** Заводит новую вершину в этой точке и возвращает её номер. */
    int addVertex(Coordinate at);
}
