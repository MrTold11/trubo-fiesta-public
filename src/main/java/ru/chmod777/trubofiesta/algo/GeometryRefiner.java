package ru.chmod777.trubofiesta.algo;

import org.locationtech.jts.geom.Coordinate;

import java.util.List;

/**
 * Доводка готовой ломаной участка. Поиск трассы обычно ведётся в каком-то упрощённом
 * пространстве — на сетке, по видимым вершинам, по коридорам, — и его результат почти всегда
 * можно сделать короче и ровнее, не нарушив правил. Как именно, зависит от алгоритма,
 * поэтому доводка тоже его часть.
 *
 * Оценка варианта вызывает доводчик один раз на цепочку и берёт возвращённую ломаную как есть:
 * проверять правила обязан сам доводчик.
 */
public interface GeometryRefiner {

    /** Доведённая ломаная. Вернуть исходную — законный ответ. */
    List<Coordinate> refine(RefineRequest request, List<Coordinate> pts);

    /** Сколько срезок сделано за всё время работы доводчика. */
    default int shortcuts() {
        return 0;
    }

    /** Сколько эти срезки сэкономили, руб. по формуле показателя. */
    default double shortcutGainRubles() {
        return 0;
    }
}
