package ru.chmod777.trubofiesta.approach;

import org.locationtech.jts.geom.Coordinate;

/**
 * Один возможный подход к точке подключения ОКС: через какую стену труба выходит и куда
 * она должна прийти. Раздел 2.2 допускает один финальный прямой участок от ближайшей
 * к точке границы полигона до самой точки, и отступ к своему полигону на этот участок
 * не распространяется.
 *
 * Подходов у одной точки несколько, и это не запас на всякий случай:
 *
 * <ul>
 *   <li>ближайшая граница полигона может быть не одна — две стены отстоят от точки
 *       одинаково или почти одинаково, и обе законны;</li>
 *   <li>за ближайшей стеной может вплотную стоять соседний ОКС, и тогда финальный участок
 *       не помещается в его минимальное расстояние. Такой подход помечен как несвободный
 *       ({@link #free}), и его причина записана в {@link #blockedBy}.</li>
 * </ul>
 *
 * Какой подход использовать, решает алгоритм: обычно он заводит вход в дом с каждого
 * годного подхода и даёт выбрать поиску по стоимости.
 *
 * Нормализация считает подходы один раз до трассировки, с отступом по наименьшему диаметру
 * справочника. Для участка большего диаметра точка отодвигается методом {@link #at(double)}.
 */
public class Approach {

    /** Точка подключения ОКС. */
    public String pointId;
    public Coordinate point;
    /** Основание нормали на стене, через которую идёт выход. */
    public Coordinate wall;
    /** Единичный вектор нормали, от точки наружу. */
    public double[] direction;
    /** От точки подключения до наружной грани стены вдоль нормали, м. */
    public double wallDistance;
    /** Длина перпендикуляра из точки на эту стену, м. По ней стена и выбрана ближайшей. */
    public double footDistance;
    /** Отступ, при котором посчитана {@link #at}: наименьший диаметр справочника, м. */
    public double clearance;
    /** Точка за зоной минимального расстояния, куда должна подойти труба. */
    public Coordinate at;
    /** Выход по нормали к стене. Ложь — запасное направление, когда нормального нет. */
    public boolean normal;
    /** Выход через стену внутреннего двора-колодца. */
    public boolean courtyard;
    /**
     * Это одна из ближайших к точке стен, как требует раздел 2.2. Ложь означает подход
     * через стену подальше: он законен только как запасной, когда ближайшие перекрыты.
     */
    public boolean nearest;
    /**
     * Финальный прямой участок помещается в минимальные расстояния до чужих объектов.
     * Проверено при наименьшем диаметре справочника: если не помещается даже так, подход
     * невозможен ни при каком диаметре.
     */
    public boolean free;
    /** Чем перекрыт подход, если он не свободен. */
    public String blockedBy;

    /** Точка подхода для другого отступа: труба большего диаметра отходит от стены дальше. */
    public Coordinate at(double otherClearance) {
        double distance = wallDistance + otherClearance;
        return new Coordinate(point.x + direction[0] * distance, point.y + direction[1] * distance);
    }

    /** Длина финального прямого участка от точки подхода до точки подключения, м. */
    public double length() {
        return point.distance(at);
    }
}
