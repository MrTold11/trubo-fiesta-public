package ru.chmod777.trubofiesta.settings;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;

/**
 * Параметры расчёта. Сюда вынесено всё, что в техническом приложении, разъяснениях и
 * конкурсном наборе трактуется неоднозначно: вместо того чтобы выбрать одну трактовку
 * и зашить её в алгоритм, сервис умеет считать в обеих, а переключатель лежит в
 * веб-интерфейсе. Значения по умолчанию — рекомендация команды.
 *
 * Неизвестные поля пропускаются: в базе лежат параметры старых расчётов, и после
 * удаления параметра такие задания всё равно должны открываться.
 */
@JsonIgnoreProperties(ignoreUnknown = true)
public class CalcSettings {

    // --- Разбор входа ----------------------------------------------------------------

    /** Допуск склейки концов участков существующей сети в один узел, м. */
    public double snapTolerance = 1.0;
    /** Условный диаметр существующей камеры, если его нет: максимум из примыкающих участков. */
    public boolean chamberDnFromSegments = true;
    /**
     * Тип ограничения вне справочника: IGNORE — не учитывать (по умолчанию), FORBID — считать
     * запретной зоной. Обязательны только типы таблицы 2 (ответ 9), а проверочные данные
     * придут из рабочих систем: чужой тип с запретом перекрыл бы всю территорию.
     */
    public String unknownRestriction = "IGNORE";

    // --- Присоединение к существующей сети --------------------------------------------

    /** Шаг кандидатов присоединения вдоль существующего участка, м. */
    public double tieInStep = 10.0;
    /** Радиус, в котором присоединяемся в существующую камеру, м (раздел 2.4). */
    public double tieInChamberRadius = 10.0;
    /** Предельное число участков, примыкающих к одной камере. */
    public int chamberMaxBranches = 4;
    /**
     * Наименьший угол между новой трубой и существующей в точке присоединения, градусы.
     * Из камеры труба уходит в любую сторону, но положе этого угла она идёт вдоль
     * существующей трубы ближе минимального расстояния.
     */
    public double tieInMinAngle = 20.0;
    /** Разрешить присоединение непосредственно в источник. */
    public boolean allowTieInToSource = false;
    /**
     * Ставить кандидат присоединения там, где нормаль от точки подключения (и перпендикуляры
     * к ней из точки подхода) пересекает существующую трубу. Кандидаты с шагом вдоль трубы
     * стоят где придётся, и трасса к дому напротив трубы получала скос; такой кандидат даёт
     * ввод одним отрезком.
     */
    public boolean approachTieIns = true;

    // --- Трассировка -----------------------------------------------------------------

    /**
     * Какой алгоритм трассировки использовать. Все они строят трассу по одной сетке в осях
     * застройки и различаются тем, как ищут дерево подключения:
     *
     * OCTOGRID — базовый: выход из дома через любую годную стену, улучшение перестановками
     * порядка вставки. OCTONORMAL — вход строго в назначенные точки подхода по нормали.
     * STEINERFIX — цена ствола уточняется итерациями до неподвижной точки. TREELS — улучшение
     * выемкой и пересборкой прямо по дереву. Неизвестный ключ означает алгоритм по умолчанию.
     */
    public String algorithm = "OCTOGRID";
    /**
     * Сколько уточняющих итераций делает STEINERFIX. На каждой поля стоимости пересчитываются
     * по расходам предыдущего дерева; итерации прекращаются раньше, если показатель перестал
     * улучшаться. Ноль оставляет обычный однопроходный расчёт.
     */
    public int steinerIterations = 3;

    /** Шаг сетки трассировки, м. Меньше — точнее проходы между домами, но дольше расчёт. */
    public double gridStep = 2.0;
    /**
     * Оси сетки: BUILDINGS — вдоль преобладающего направления стен, NORTH — по сторонам света.
     * NORTH в интерфейсе не показывается: выходы из домов не совпадают с осями, и появляются
     * нестандартные отводы. Оставлен для сравнения на защите.
     */
    public String gridOrientation = "BUILDINGS";
    /** Разрешить диагональные ходы под 45 градусов к осям. */
    public boolean diagonals = true;
    /**
     * Цена одного поворота трассы в метрах трубы. Больше — меньше изломов. Значение 10 давало
     * на конкурсном наборе деревья хуже по показателю и сильный разброс между зёрнами,
     * 3–5 — стабильно лучше при том же числе поворотов в инженерном варианте.
     */
    public double turnPenalty = 5.0;
    /**
     * Доплата за ступеньку — два поворота с коротким отрезком между ними, в метрах трубы.
     * Приложение требует трассу без мелких изломов, зигзагов и ступенчатых фрагментов.
     */
    public double jogPenalty = 40.0;
    /** Отрезок между двумя поворотами короче этого считается ступенькой, м. */
    public double minStraightRun = 3.0;
    /**
     * Наименьший угол между двумя участками, отходящими от одного узла, градусы. Меньше —
     * две ветки идут по одному коридору и физически лежат в одной траншее. В приложении
     * прямо не сказано, но новые участки не должны пересекаться и накладываться. С 15°
     * проходили отходы веток в 18–25° к стволу: формально врозь, физически рядом с ним
     * (замер 28.09), поэтому по умолчанию 30°.
     */
    public double minBranchAngle = 30.0;
    /** Длина луча из точки подключения или места присоединения до выхода на сетку, м. */
    public double rayLength = 150.0;
    /** Насколько стена может отклоняться от оси сетки, чтобы выход из дома шёл точно по оси, градусы. */
    public double exitSnapDeg = 5.0;
    /**
     * Насколько стены могут отличаться по расстоянию до точки подключения, чтобы обе считались
     * ближайшими, м. Раздел 2.2 говорит про ближайшую границу полигона, но точка часто стоит
     * в углу, почти одинаково далеко от двух стен, и обе одинаково законны. Тогда у точки
     * получается несколько подходов, а выбрать между ними — дело алгоритма.
     *
     * По умолчанию 0,5 м — прежняя константа. С 1,0 м на конкурсном наборе у домов появлялись
     * лишние выходы, и жадное дерево уходило в худшую сторону: лучший S 13,135 → 13,241,
     * дешёвая стратегия 13,135 → 13,445 (замер 27.09).
     */
    public double approachTolerance = 0.5;
    /** Считать полигон подключаемого дома препятствием для трасс к другим домам. */
    public boolean futureOksAsObstacle = true;
    /**
     * Что считать своим домом, если объект restriction содержит несколько полигонов:
     * CORPUS — корпус с точкой и примыкающие к нему вплотную части, FEATURE — весь объект
     * одного адреса, PART — только полигон с точкой.
     */
    public String ownBuildingScope = "CORPUS";
    /**
     * Через какую стену выходить из здания: NEAREST — ближайшую к точке, ANY — любую рядом,
     * по стоимости. Раздел 2.2 требует участок от ближайшей к точке границы полигона.
     */
    public String exitWall = "NEAREST";
    /**
     * Разрешить выход через другую стену, если через ближайшую выйти нельзя. Раздел 2.2
     * такого не допускает, поэтому по умолчанию выключено: точка считается недостижимой.
     */
    public boolean exitFallback = false;
    /** Минимальные расстояния считать от внешней границы габарита пары труб, а не от оси. */
    public boolean clearanceFromGabarit = true;
    /** Игнорировать полигоны ограничений мельче этой площади, м². */
    public double minRestrictionArea = 0.0;
    /** Часть здания меньше этой площади — малое сооружение, а не здание, м². */
    public double smallObjectArea = 5.0;
    /** Отступ от малого сооружения, м. От здания — по таблице 2. */
    public double smallObjectClearance = 1.0;
    /** Упрощение границ препятствий, м. Больше — быстрее, грубее; запас закладывается в отступ. */
    public double obstacleSimplify = 0.1;

    // --- Правила, которые трактуются по-разному ---------------------------------------

    /**
     * Предельная длина одного Ду: PATH — отдельно по каждому непрерывному пути (ответ 2),
     * SUM — сумма всех участков одного Ду, включая ветки. Правильный ответ — PATH,
     * SUM оставлен, чтобы показать разницу.
     */
    public String lengthLimitMode = "PATH";
    /** Что делать при превышении: UPSIZE — поднять Ду до подходящего, WARN — только предупредить. */
    public String lengthLimitAction = "UPSIZE";
    /** Две точки подключения в одном здании: SEPARATE — разные цели (ответ 4), MERGE — одна. */
    public String pointsInSameBuilding = "SEPARATE";

    // --- Доводка трассы --------------------------------------------------------------

    /**
     * Только отводы 45° и 90°, в том числе в узлах. Приложение допускает любой угол до 90°
     * без удорожания (2.1), поэтому по умолчанию выключено: доводка спрямляет всё, что
     * законно и дешевле. Включается, если инженеру нужна разводка строго стандартными отводами.
     */
    public boolean standardAnglesOnly = false;
    /**
     * Наименьший выигрыш срезки с нестандартным углом, руб., с длиной трассы, переведённой
     * в рубли по формуле показателя. Срезка, после которой все углы остаются 45° и 90°, и
     * срезка, убирающая дефект (заглушку, зигзаг, горб), принимаются при любом выигрыше:
     * инженер чертит стандартными отводами и режет угол только ради заметной экономии.
     * Ноль — любая законная срезка, которая уменьшает показатель (замер 28.09: 13,070 при
     * семи углах не 45/90 в первом варианте против 13,139 при нуле таких углов). Три миллиона
     * — это 12–15 м трубы: все срезки под произвольным углом на конкурсном наборе экономили
     * 5–8 м на 80–190 м участка, то есть наклоняли длинный ствол на 10° ради пяти метров.
     */
    public double shortcutMinGain = 3_000_000;
    /**
     * Сколько сервис готов доплатить за вид трассы в одном месте, руб. по формуле показателя:
     * перенос камеры на линию ствола и замена двух-трёх поворотов одним стандартным
     * принимаются, даже если трасса от этого чуть длиннее. Ноль — только если показатель не
     * растёт: тогда на конкурсном наборе остаётся заглушка 1,6 м у камеры дома 11, перенос
     * которой дороже на 0,0004 показателя. Миллион на конкурсном наборе — 0,028 показателя.
     */
    public double beautyAllowance = 1_000_000;
    /**
     * Две камеры ветвления ближе этого расстояния по трассе сливаются в одну, если это
     * дешевле и не нарушает правил, м.
     */
    public double chamberMergeDistance = 15.0;
    /**
     * Ставить камеру ветвления на линию ствола напротив ветки: ствол проходит через неё
     * прямо, ввод в дом идёт одним отрезком по нормали. Без этого камера остаётся там, где
     * к стволу подошла трасса, с заглушками и горбами вокруг неё.
     */
    public boolean alignChambers = true;

    // --- Поиск вариантов -------------------------------------------------------------

    /** Качество поиска: FAST, NORMAL или THOROUGH. Определяет число запусков. */
    public String quality = "NORMAL";
    /** Режим: MULTISTART — много запусков с разным порядком, GREEDY — один жадный проход. */
    public String planMode = "MULTISTART";
    /** Число запусков. Ноль означает «взять из качества поиска». */
    public int starts = 0;
    /** Улучшать готовое дерево перестановками порядка точек подключения. */
    public boolean relink = true;
    /** Зерно случайности. Фиксировано, чтобы повторный запуск давал тот же результат. */
    public long seed = 20260916L;
    /** Сколько вариантов отдавать, не больше трёх по условию приложения. */
    public int variantCount = 3;
    /** Насколько должны различаться места присоединения, чтобы варианты считались разными, м. */
    public double variantMinDifference = 10.0;

    // --- Выгрузка --------------------------------------------------------------------

    /** Явно писать depth_start и depth_end со значением null в двумерной задаче. */
    public boolean writeNullDepth = true;
    /** Проверять результат встроенным контролем перед выдачей. */
    public boolean selfCheck = true;

    /** Копия параметров: второй заход поиска отличается только ценой поворота. */
    public CalcSettings copy() {
        com.fasterxml.jackson.databind.ObjectMapper mapper = new com.fasterxml.jackson.databind.ObjectMapper();
        return mapper.convertValue(mapper.convertValue(this, java.util.Map.class), CalcSettings.class);
    }

    /** Столько точек подключения считаются набором обычного размера: бюджет поиска полный. */
    public static final int FULL_BUDGET_POINTS = 20;

    /**
     * Сколько запусков делать для набора из points точек. Каждый запуск строит дерево на все
     * точки, поэтому его цена растёт с их числом; чтобы расчёт не рос квадратично, на больших
     * наборах бюджет делится пропорционально размеру, но не ниже 24 запусков. Явно заданное
     * число запусков (starts) не масштабируется.
     */
    public int effectiveStarts(int points) {
        int base = effectiveStarts();
        if (starts > 0 || points <= FULL_BUDGET_POINTS) {
            return base;
        }
        return Math.max(24, base * FULL_BUDGET_POINTS / points);
    }

    /** Сколько запусков делать с учётом выбранного качества поиска. */
    public int effectiveStarts() {
        if (starts > 0) {
            return starts;
        }
        // Поля стоимости дороже самого поиска: на 17 домах поля — 25 с, 200 стартов — 20 с и
        // 600 стартов — те же 20 с, а показатель на 0,35 % лучше (замер 28.09). Поэтому обычное
        // качество — 600 стартов, а не 200.
        if ("FAST".equals(quality)) {
            return 40;
        }
        if ("THOROUGH".equals(quality)) {
            return 1500;
        }
        return 600;
    }
}
